// server/prompts.test.ts — tests for what the instructions step writes.
//
// What: checks claudeFileFor, which decides the new content of a folder's
// CLAUDE.md; taking beads' generated blocks out of a text; telling our
// rules from an earlier version of them and from a version the owner
// edited; and that the rules stand on their own.
//
// Why: this step writes into the user's repository. It must never throw
// away text the user wrote, and never create a CLAUDE.md (the user's
// decision). Since bead-bb-c9l.8 it also removes text, beads' own, and the
// one thing that makes that safe is that only text between beads' markers
// goes.
import assert from "node:assert/strict";
import { test } from "node:test";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  AIRBENDER_RULES,
  RULES_START,
  agentsFileWith,
  beadsLeftovers,
  claudeFileFor,
  hasBeadsBlocks,
  rulesIn,
  withoutBeadsBlocks,
} from "./prompts.ts";

/** A CLAUDE.md as `bd init` generates it, with its unfilled placeholders. */
const GENERATED = `# Project Instructions for AI Agents

<!-- BEGIN BEADS INTEGRATION v:1 profile:minimal hash:1105d646 -->
## Beads Issue Tracker
<!-- END BEADS INTEGRATION -->
## Build & Test

_Add your build and test commands here_

## Architecture Overview

_Add a brief overview of your project architecture_

## Conventions & Patterns

_Add your project-specific conventions here_
`;

test("no CLAUDE.md, or an empty one, is left alone", () => {
  assert.equal(claudeFileFor(null), null);
  assert.equal(claudeFileFor("  \n"), null);
});

test("beads' generated, unfilled file becomes a pointer to AGENTS.md", () => {
  const next = claudeFileFor(GENERATED);
  assert.ok(next !== null);
  assert.match(next, /^@AGENTS\.md$/mu);
  assert.doesNotMatch(next, /BEADS INTEGRATION/u);
});

test("a file the user has written in is kept, less beads' block, with the two pointers added", () => {
  const edited = GENERATED.replace(
    "_Add your build and test commands here_",
    "npm test",
  );
  const next = claudeFileFor(edited);
  assert.ok(next !== null);
  assert.ok(next.startsWith("@AGENTS.md\n@FACTS.md\n\n# Project Instructions for AI Agents\n"));
  assert.doesNotMatch(next, /BEADS INTEGRATION|Beads Issue Tracker/u);
  assert.match(next, /## Build & Test\n\nnpm test\n/u);
  // No beads block in it: the owner's text, to the letter, after the lines.
  const own = "# Mine\n\nUse tabs.\n";
  assert.equal(claudeFileFor(own), `@AGENTS.md\n@FACTS.md\n\n${own}`);
});

test("a file that points at both is not touched; one that points at AGENTS.md only gets the facts line", () => {
  const pointer = claudeFileFor(GENERATED)!;
  assert.match(pointer, /^@AGENTS\.md\n@FACTS\.md$/mu);
  assert.equal(claudeFileFor(pointer), null);
  assert.equal(claudeFileFor("# Mine\n@AGENTS.md\n@FACTS.md\n"), null);
  // The pointer an earlier version wrote: one line added, after the first.
  assert.equal(
    claudeFileFor("# Mine\n\n@AGENTS.md\n\nOnly a pointer.\n"),
    "# Mine\n\n@AGENTS.md\n@FACTS.md\n\nOnly a pointer.\n",
  );
});

test("Airbender's rules start with the marker the tab looks for", () => {
  assert.ok(AIRBENDER_RULES.startsWith(RULES_START));
});

// --- Our instructions in place of beads' (bead-bb-c9l.8) ---

/** An AGENTS.md as `bd init` and `bd setup codex` leave it, with the owner's text around. */
const WITH_BEADS = `# Agent Instructions

My own opening.

## Quick Reference

\`\`\`bash
bd ready              # Find available work
bd close <id>         # Complete work
\`\`\`

<!-- BEGIN BEADS INTEGRATION v:1 profile:minimal hash:1105d646 -->
## Beads Issue Tracker

Use bd. Close finished work.

## Session Completion

Close finished work, then push.
<!-- END BEADS INTEGRATION -->

## Between

Mine, between the two.

<!-- BEGIN BEADS CODEX SETUP: generated by bd setup codex -->
## Beads Issue Tracker

Use the beads skill.
<!-- END BEADS CODEX SETUP -->

## After

Mine, after.
`;

test("beads' marked blocks are taken out, and nothing else changes", () => {
  assert.equal(hasBeadsBlocks(WITH_BEADS), true);
  const out = withoutBeadsBlocks(WITH_BEADS);
  assert.equal(hasBeadsBlocks(out), false);
  assert.equal(
    out,
    `# Agent Instructions

My own opening.

## Quick Reference

\`\`\`bash
bd ready              # Find available work
bd close <id>         # Complete work
\`\`\`

## Between

Mine, between the two.

## After

Mine, after.
`,
  );
  // Every line that is left was there before, in the same order.
  const before = WITH_BEADS.split("\n");
  let at = 0;
  for (const line of out.split("\n")) {
    at = before.indexOf(line, at);
    assert.notEqual(at, -1, line);
    at += 1;
  }
  // No block: the very same text, so nothing is rewritten.
  const plain = "# Mine\n\n\n\nOdd spacing kept.\n";
  assert.equal(withoutBeadsBlocks(plain), plain);
  // A file that was only beads' block.
  assert.equal(
    withoutBeadsBlocks("<!-- BEGIN BEADS INTEGRATION v:9 -->\nx\n<!-- END BEADS INTEGRATION -->\n"),
    "\n",
  );
});

test("beads' text without markers is named, not removed", () => {
  assert.deepEqual(beadsLeftovers(withoutBeadsBlocks(WITH_BEADS)), ["Quick Reference"]);
  assert.deepEqual(
    beadsLeftovers(
      "# Agent Instructions\n\nThis project uses **bd** (beads) for issue tracking. Run `bd prime` for full workflow context.\n\n## Session Completion\n\nx\n",
    ),
    ["the opening lines about bd prime", "Session Completion"],
  );
  // The owner's own "Quick Reference" that has nothing to do with beads.
  assert.deepEqual(beadsLeftovers("## Quick Reference\n\nnpm test\n"), []);
  assert.deepEqual(beadsLeftovers("# Mine\n"), []);
});

test("the rules stand on their own: no word about beads' text beside them, the commands named, the facts file", () => {
  assert.doesNotMatch(AIRBENDER_RULES, /take precedence|elsewhere in this file/u);
  for (const command of ["bd show <id>", "bd comments <id>", "bd update <id>", "bd comment <id>", "bd create", "bd dep add"]) {
    assert.ok(AIRBENDER_RULES.includes(command), command);
  }
  assert.match(AIRBENDER_RULES, /Standing facts are in `FACTS\.md`/u);
  assert.match(AIRBENDER_RULES, /Never close an issue with `bd close`/u);
});

/** The rules as they were written before this version, by fingerprint. */
const VERSION_1 = "bcf270710cd722894f17bde63d8aa46944be782add371ede632d38a44bb47783";

test("an earlier version's block is recognised, an edited one is the owner's", () => {
  assert.equal(rulesIn("# Mine\n"), "none");
  assert.equal(rulesIn(`# Mine\n\n${AIRBENDER_RULES}`), "current");
  // Changed by hand, in any way: theirs.
  assert.equal(
    rulesIn(AIRBENDER_RULES.replace("Never close an issue", "Close an issue")),
    "edited",
  );
  // A block no version of ours ever was.
  assert.equal(
    rulesIn(`${RULES_START}\n## My own rules\n<!-- airbender:rules:end -->\n`),
    "edited",
  );
  // The current text must not be listed as an earlier one: when the rules
  // change, the old text's fingerprint is added and the version raised.
  const now = createHash("sha256")
    .update(AIRBENDER_RULES.replace(/\s+/gu, " ").trim())
    .digest("hex");
  assert.notEqual(now, VERSION_1);
});

test("an earlier version of ours is replaced where it stands, and nothing around it moves", () => {
  // The rules exactly as version 1 of this plugin wrote them into
  // repositories, kept as a file so that this can be tried for real.
  const v1 = readFileSync(
    join(dirname(fileURLToPath(import.meta.url)), "fixtures", "rules-v1.md"),
    "utf8",
  );
  const before = `# Mine\n\nAbove.\n\n${v1}\n## After\n\nBelow.\n`;
  assert.equal(rulesIn(before), "old");
  const after = agentsFileWith(before);
  assert.equal(after, `# Mine\n\nAbove.\n\n${AIRBENDER_RULES}\n## After\n\nBelow.\n`);
  assert.equal(rulesIn(after), "current");
  assert.equal(agentsFileWith(after), after);
});

test("the rules are added at the end, an edited block is left, and adding twice changes nothing", () => {
  assert.equal(agentsFileWith(""), AIRBENDER_RULES);
  const mine = "# Mine\n\nMy own text.\n";
  const once = agentsFileWith(mine);
  assert.equal(once, `# Mine\n\nMy own text.\n\n${AIRBENDER_RULES}`);
  assert.equal(agentsFileWith(once), once);
  const edited = `# Mine\n\n${RULES_START}\n## My own rules\n<!-- airbender:rules:end -->\n\n## After\n`;
  assert.equal(agentsFileWith(edited), edited);
  // The whole switch-over on beads' file: blocks out, rules in, the rest kept.
  const switched = agentsFileWith(withoutBeadsBlocks(WITH_BEADS));
  assert.equal(rulesIn(switched), "current");
  assert.equal(hasBeadsBlocks(switched), false);
  assert.ok(switched.startsWith("# Agent Instructions\n\nMy own opening.\n"));
  assert.ok(switched.includes("## After\n\nMine, after.\n\n" + RULES_START));
});
